        function tf = isinteractive(force)
            % true if a person can answer dialogs and close windows. In "matlab -batch"
            % (scripts run by agents, CI) uiwait/waitfor would wait forever.
            % isinteractive(false) simulates batch mode (tests), isinteractive([]) resets.
            persistent forced
            if nargin
                forced = force;
            end
            if isempty(forced)
                tf = ~batchStartupOptionUsed;
            else
                tf = forced;
            end
        end

        function requireinteractive(what,alternative)
            % Error (instead of hanging) if a method is about to wait for a person
            if ~drEEMtoolbox.isinteractive
                throwAsCaller(MException("drEEM:needsInteractiveSession", ...
                    "%s waits for a person to close a window, which never happens in " + ...
                    "batch mode (matlab -batch). Instead: %s", what, alternative))
            end
        end

        function openWritableDoc(relPath)
            arguments
                relPath (1,:) char = 'doc/GettingStarted.m'
            end

            src = fullfile(drEEMtoolbox.rootfolder, relPath);
            if ~isfile(src)
                error('drEEM:docFileNotFound', 'Could not find "%s" under the drEEM toolbox root.', relPath)
            end

            destBase = userpath;
            if isempty(destBase) || ~isfolder(destBase)
                destBase = tempdir;   % same fallback MATLAB's own example machinery uses
            end
            destFolder = fullfile(destBase, 'drEEM_tutorials');
            if ~isfolder(destFolder)
                mkdir(destFolder)
                T=["This folder was automatically generated by the drEEM toolbox documentation and contains live scripts you can edit (but need to rename to have persistent changes)",newline,...
                    "this is the end of this file."]; 
                FN = 'readme.txt';  % better to use fullfile(path,name) 
                fid = fopen(fullfile(destFolder,FN),'w');    % open file for writing (overwrite if necessary)
                fprintf(fid,'%s',T);          % Write the char array, interpret newline as new line
                fclose(fid);
            end

            [~, name, ext] = fileparts(relPath);
            dest = fullfile(destFolder, [name ext]);   % flatten into destFolder regardless of source subfolder
            
            copyfile(src, dest, 'f');
            
            open(dest)
        end

    end

