    properties (GetAccess = public,SetAccess = {?drEEMstatus, ?drEEMdataset})
        spectralCorrection ...
            {mustBeText,...
            mustBeMember(spectralCorrection,...
            ["not applicable (no data)","unknown","not applied","applied by instrument software","applied by toolbox"])} = "unknown"
        IFEcorrection ...
            {mustBeText,...
            mustBeMember(IFEcorrection,...
            ["not applicable (no data)","unknown","not applied","applied by instrument software","applied by toolbox",...
            "deemed unnecessary"])} = "unknown"
        blankSubtraction ...
        {mustBeText,...
            mustBeMember(blankSubtraction,...
            ["not applicable (no data)","unknown","not applied","applied by instrument software","applied by toolbox"])} = "unknown"
        signalCalibration ...
        {mustBeText,...
            mustBeMember(signalCalibration,...
            ["not applicable (no data)","unknown","not applied","applied by instrument software (QSU)",...
             "applied by instrument software (RU)",...
             "applied by toolbox (RU)","applied by toolbox (QSU)"])} = "unknown"
        scatterTreatment ...
        {mustBeText,...
            mustBeMember(scatterTreatment,...
            ["not applicable (no data)","unknown","not applied","applied by instrument software","applied by toolbox"])} = "unknown"
        signalScaling ...
             = ""
        absorbanceUnit ...
            {mustBeText,...
            mustBeMember(absorbanceUnit,...
            ["not applicable (no data)","unknown","absorbance per cm","absorbance per 5 cm","absorbance per 10 cm","napierian absorption coefficient","linear decadic absorption coefficient"])} = "unknown"
        suppSpectraInfo ...
            = "unnown"
    end

    methods (Static=true)
        function obj=drEEMstatus(status)
            arguments
                % Status (optional input)
                status.spectralCorrection ...
                    {mustBeText,...
                    mustBeMember(status.spectralCorrection,...
                    ["not applicable (no data)","unknown","not applied","applied by instrument software","applied by toolbox"])} = "unknown"
                status.IFEcorrection ...
                    {mustBeText,...
                    mustBeMember(status.IFEcorrection,...
                    ["not applicable (no data)","unknown","not applied","applied by instrument software","applied by toolbox",...
                    "deemed unnecessary"])} = "unknown"
                status.blankSubtraction ...
                    {mustBeText,...
                    mustBeMember(status.blankSubtraction,...
                    ["not applicable (no data)","unknown","not applied","applied by instrument software","applied by toolbox"])} = "unknown"
                status.signalCalibration ...
                    {mustBeText,...
                    mustBeMember(status.signalCalibration,...
                    ["not applicable (no data)","unknown","not applied","applied by instrument software (QSU)",...
                    "applied by instrument software (RU)",...
                    "applied by toolbox (RU)","applied by toolbox (QSU)"])} = "unknown"
                status.scatterTreatment ...
                    {mustBeText,...
                    mustBeMember(status.scatterTreatment,...
                    ["not applicable (no data)","unknown","not applied","applied by instrument software","applied by toolbox"])} = "unknown"
                status.signalScaling ...
                    = "unknown"
                status.absorbanceUnit ...
                    {mustBeText,...
                    mustBeMember(status.absorbanceUnit,...
                    ["not applicable (no data)","unknown","absorbance per cm","absorbance per 5 cm","absorbance per 10 cm","napierian absorption coefficient","linear decadic absorption coefficient"])} = "unknown"
                status.suppSpectraInfo ...
                    = "unknown"
            end

            
            flds=fieldnames(status);
            for j=1:numel(flds)
                obj.(flds{j})=status.(flds{j});
            end

        end
        
        function obj = change(obj,prop,value)
            arguments
                obj {mustBeA(obj,"drEEMstatus")}
                prop ...
                    {mustBeMember(prop,...
                    ["spectralCorrection","IFEcorrection","blankSubtraction",...
                    "signalCalibration","scatterTreatment","signalScaling","absorbanceUnit","suppSpectraInfo"])}
                value {mustBeText}
            end

            obj.(prop)=value;

        end

        function [values,status_props] = getCurrent(obj)
            status_props=properties(obj);
            for j=1:numel(status_props)
                values{j,1}=char(obj.(status_props{j}));

            end
        end

        function [result,message] = isequal(a,b)
            arguments
                a (1,1) {mustBeA(a,'drEEMstatus')}
                b (1,1) {mustBeA(b,'drEEMstatus')}
            end
            cnt=0;
            props=fieldnames(a);
            message='';
            for j=1:numel(props)
                if not(matches(a.(props{j}),b.(props{j})))
                    if cnt==0
                        message=[message,'The drEEMdataset status''es are <strong>not identical</strong>. See below for details:\n'];
                    end
                    cnt=cnt+1;
                    message=[message,'   <strong>',props{j},'</strong>: "',char(a.(props{j})),'" vs. "',char(b.(props{j})),'"\n'];
                end
            end

            if cnt==0
                message='success';
                result=true;
            else
                result=false;
            end

        end
    end
end